# make stub C source for exporting TVP's internal functions.
#
# Python port of common/base/makestub.pl (Perl + Compress::Zlib + Digest::MD5).
# Byte-exact replacement: reproduces FuncStubs.{h,cpp} and tp_stub/tp_stub.{h,cpp}
# identically to the Perl original.
#
# Files are read/written as latin-1 with newline='' so every byte (incl. UTF-8
# Japanese comment bytes and any CR) is preserved verbatim, mirroring Perl's
# byteswise slurp/print with no PerlIO translation.
#
# usage: python gen_tpstub.py [core_base_dir]
#   core_base_dir defaults to two levels up from this script (i.e. src/core when
#   the script lives in common/base). Outputs (written only when the bytes
#   change; byte-identical to the former makestub.pl):
#     {core}/common/base/FuncStubs.h
#     {core}/common/base/FuncStubs.cpp
#     {core}/tp_stub/tp_stub.h
#     {core}/tp_stub/tp_stub.cpp
#
# After regenerating {core}/tp_stub/tp_stub.{h,cpp}, copy them into the
# plugins' tp_stub submodule as before (see README / tp_stub notes).


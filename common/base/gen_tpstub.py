def _strip(s):
    # Perl: s/^\s*(.*?)\s*$/$1/  (no /s, no /m)
    return re.sub(r'^\s*(.*?)\s*$', r'\1', s, count=1, flags=re.ASCII)


def normalize_string(s):
    # Perl:
    #   s/^\s*(.*?)\s*$/$1/           (strip; subsumed by the tokenize below)
    #   s/\*\*/\* \*/g  (twice)       (** -> * *)
    #   @a = split(/\s|\b/, $s); keep non-empty non-ws; join ' '
    # The kept tokens of split(/\s|\b/) are exactly the maximal runs of word
    # chars OR of non-word/non-space chars, so findall reproduces them.
    s = re.sub(r'\*\*', '* *', s)
    s = re.sub(r'\*\*', '* *', s)
    tokens = re.findall(r'\w+|[^\w\s]+', s, flags=re.ASCII)
    return ' '.join(tokens)


def _perl_split_re(pattern, s):
    # Perl split(/pattern/, $s): '' -> (); trailing empty fields removed.
    # (Our pattern \s*,\s* always requires a comma, so no zero-width concerns.)
    if s == '':
        return []
    parts = re.split(pattern, s)
    while parts and parts[-1] == '':
        parts.pop()
    return parts


def _perl_split_comma(s):
    # Perl split(/,/, $s): '' -> (); trailing empty fields removed (LIMIT=0).
    if s == '':
        return []
    parts = s.split(',')
    while parts and parts[-1] == '':
        parts.pop()
    return parts


def get_arg_names(args):
    out = ''
    for arg in _perl_split_comma(args):
        arg = _strip(arg)
        m = re.match(r'^(.*)=(.*)$', arg, flags=re.ASCII)  # drop default value
        if m:
            arg = m.group(1)
        arg = _strip(arg)
        # Perl: $arg =~ /(\w+)$/  -- on failure $1 keeps the value set by the
        # immediately-preceding successful match (the _strip above => arg).
        mm = re.search(r'(\w+)$', arg, flags=re.ASCII)
        piece = mm.group(1) if mm else arg
        if out != '':
            out += ', '
        out += piece
    return out


def except_arg_names(args):
    out = ''
    for arg in _perl_split_comma(args):
        arg = _strip(arg)
        m = re.match(r'^(.*)=(.*)$', arg, flags=re.ASCII)
        if m:
            arg = m.group(1)
        arg = _strip(arg)
        arg = re.sub(r'(.*?)(\w+)$', r'\1', arg, count=1, flags=re.ASCII)  # drop trailing name
        arg = _strip(arg)  # $1 becomes the stripped type; Perl uses $1 here
        if out != '':
            out += ','
        out += normalize_string(arg)
    return out


def get_ret_type(type_, prefix):
    if type_ == prefix + "_METHOD_RET_EMPTY":
        return 'void'
    m = re.search(re.escape(prefix) + r'_METHOD_RET\((.*?)\)', type_, flags=FLAGS)
    if m:
        return normalize_string(m.group(1))
    return normalize_string(type_)


def make_func_stub(rettype, name, arg, type_, prefix, isconst, isstatic, envname=None):
    global num
    rettype = rettype.replace('\n', ' ').replace('\t', ' ')
    name = name.replace('\n', ' ').replace('\t', ' ')
    arg = arg.replace('\n', ' ').replace('\t', ' ')

    is_ret_macro = rettype.startswith(prefix + "_METHOD_RET")

    func_exp_name = (
        ('' if is_ret_macro else normalize_string(rettype) + ' ') +
        type_ + '::' + normalize_string(name) + '(' + except_arg_names(arg) + ')' +
        (' const' if isconst else '')
    )

    md5 = hashlib.md5(func_exp_name.encode('latin-1')).hexdigest()

    mangled = "TVP_Stub_" + md5 + "\t"
    mangled += func_exp_name
    mangled += ("\t" + get_ret_type(rettype, prefix) +
                "(STDCALL *  __TVP_Stub_" + md5 + ")(" + type_ + " *_this" +
                (', ' if arg != '' else '') + normalize_string(arg) + ")")
    mangled += ("\t" + ('' if is_ret_macro else normalize_string(rettype)) +
                " " + normalize_string(type_) + "::" + normalize_string(name) +
                "(" + normalize_string(arg) + ")")
    mangled += "\tTVP_Stub_" + md5
    mangled += "\t" + md5
    mangled += "\t" + get_arg_names(arg)
    functype = (get_ret_type(rettype, prefix) +
                "(STDCALL * __functype)(" + ("const " if isconst else "") +
                ('' if isstatic else (type_ + " *" + (', ' if arg != '' else ''))) +
                normalize_string(except_arg_names(arg)) + ")")
    mangled += "\t" + functype
    if envname:
        mangled += "\t" + envname

    noreturn = 0
    if rettype == prefix + "_METHOD_RET_EMPTY":
        noreturn = 1
    elif re.search(re.escape(prefix) + r'_METHOD_RET\((.*?)\)', rettype, flags=FLAGS):
        noreturn = 2

    rettype = get_ret_type(rettype, prefix)

    if envname:
        OFH.append("#ifdef " + envname + "\n")

    OFH.append("static ")
    OFH.append(normalize_string(rettype))
    OFH.append(" STDCALL ")
    OFH.append("TVP_Stub_" + md5)
    if isstatic:
        OFH.append("(")
    else:
        OFH.append("(" + type_ + " * _this")
        if arg != '':
            OFH.append(", ")

    OFH.append(normalize_string(arg))
    OFH.append(")\n")
    OFH.append("{\n")
    argnames = get_arg_names(arg)
    if name == type_:
        # constructor
        OFH.append("\t::new (_this) " + name + "(" + argnames + ");\n")
        h = ("\t" + normalize_string(name) + "(" + normalize_string(arg) + ")\n" +
             "\t{\n" +
             "\t\tif(!TVPImportFuncPtr" + md5 + ")\n" +
             "\t\t{\n" +
             "\t\t\tstatic char funcname[] = \"" + func_exp_name + "\";\n" +
             "\t\t\tTVPImportFuncPtr" + md5 + " = TVPGetImportFuncPtr(funcname);\n" +
             "\t\t}\n" +
             "\t\ttypedef " + functype + ";\n" +
             "\t\t((__functype)(TVPImportFuncPtr" + md5 + "))(" +
             ('' if isstatic else ("this" + (', ' if argnames != '' else ''))) + argnames + ");\n" +
             "\t}\n")
    elif name == "~" + type_:
        # destructor
        OFH.append("\t_this->" + name + "(" + argnames + ");\n")
        h = ("\t" + normalize_string(name) + "(" + normalize_string(arg) + ")\n" +
             "\t{\n" +
             "\t\tif(!TVPImportFuncPtr" + md5 + ")\n" +
             "\t\t{\n" +
             "\t\t\tstatic char funcname[] = \"" + func_exp_name + "\";\n" +
             "\t\t\tTVPImportFuncPtr" + md5 + " = TVPGetImportFuncPtr(funcname);\n" +
             "\t\t}\n" +
             "\t\ttypedef " + functype + ";\n" +
             "\t\t((__functype)(TVPImportFuncPtr" + md5 + "))(" +
             ('' if isstatic else ("this" + (', ' if argnames != '' else ''))) + argnames + ");\n" +
             "\t}\n")
    else:
        OFH.append("\t")
        OFH.append("return ")
        if isstatic:
            OFH.append(type_ + "::" + name + "(" + argnames + ");\n")
        else:
            OFH.append("_this->" + name + "(" + argnames + ");\n")
        h = ("\t" + ('static ' if isstatic else '') + ('' if noreturn else rettype + ' ') +
             normalize_string(name) + "(" + normalize_string(arg) + ")" +
             (' const' if isconst else '') + "\n" +
             "\t{\n" +
             "\t\tif(!TVPImportFuncPtr" + md5 + ")\n" +
             "\t\t{\n" +
             "\t\t\tstatic char funcname[] = \"" + func_exp_name + "\";\n" +
             "\t\t\tTVPImportFuncPtr" + md5 + " = TVPGetImportFuncPtr(funcname);\n" +
             "\t\t}\n" +
             "\t\ttypedef " + functype + ";\n" +
             "\t\t" + ('' if rettype == 'void' else 'return ') +
             "((__functype)(TVPImportFuncPtr" + md5 + "))(" +
             ('' if isstatic else ("this" + (', ' if argnames != '' else ''))) + argnames + ");\n" +
             "\t}\n")
    OFH.append("}\n")

    if envname:
        OFH.append("#else\n")
        OFH.append("static void STDCALL TVP_Stub_" + md5 + "(){}\n")
        OFH.append("#endif // " + envname + "\n")

    if envname:
        h = "#ifdef " + envname + "\n" + h + "#endif // " + envname + "\n"

    func_list.append(mangled)
    h_stub.append(h)
    num += 1


def list_func_stub(prefix, content, type_):
    p = re.escape(prefix)
    grp3 = r'\(\s*(.*?)\s*,\s*(.*?)\s*,\s*\((.*?)\)\s*\)'
    grp4 = r'\(\s*(.*?)\s*,\s*(.*?)\s*,\s*(.*?)\s*,\s*\((.*?)\)\s*\)'

    for m in re.finditer(p + r'_METHOD_DEF' + grp3, content, flags=FLAGS):
        make_func_stub(m.group(1), m.group(2), m.group(3), type_, prefix, 0, 0)
    for m in re.finditer(p + r'_CONST_METHOD_DEF' + grp3, content, flags=FLAGS):
        make_func_stub(m.group(1), m.group(2), m.group(3), type_, prefix, 1, 0)
    for m in re.finditer(p + r'_STATIC_METHOD_DEF' + grp3, content, flags=FLAGS):
        make_func_stub(m.group(1), m.group(2), m.group(3), type_, prefix, 0, 1)
    for m in re.finditer(p + r'_STATIC_CONST_METHOD_DEF' + grp3, content, flags=FLAGS):
        make_func_stub(m.group(1), m.group(2), m.group(3), type_, prefix, 1, 1)

    for m in re.finditer(p + r'_METHOD_DEF_ENV' + grp4, content, flags=FLAGS):
        make_func_stub(m.group(2), m.group(3), m.group(4), type_, prefix, 0, 0, m.group(1))
    for m in re.finditer(p + r'_CONST_METHOD_DEF_ENV' + grp4, content, flags=FLAGS):
        make_func_stub(m.group(2), m.group(3), m.group(4), type_, prefix, 1, 0, m.group(1))
    for m in re.finditer(p + r'_STATIC_METHOD_DEF_ENV' + grp4, content, flags=FLAGS):
        make_func_stub(m.group(2), m.group(3), m.group(4), type_, prefix, 0, 1, m.group(1))
    for m in re.finditer(p + r'_STATIC_CONST_METHOD_DEF_ENV' + grp4, content, flags=FLAGS):
        make_func_stub(m.group(2), m.group(3), m.group(4), type_, prefix, 1, 1, m.group(1))


def make_exp_stub(rettype, name, arg, envname=None):
    global num
    rettype = rettype.replace('\n', ' ').replace('\t', ' ')
    name = name.replace('\n', ' ').replace('\t', ' ')
    arg = arg.replace('\n', ' ').replace('\t', ' ')

    func_exp_name = (normalize_string(rettype) + ' ' +
                     '::' + normalize_string(name) + '(' + except_arg_names(arg) + ')')

    md5 = hashlib.md5(func_exp_name.encode('latin-1')).hexdigest()

    mangled = "TVP_Stub_" + md5 + "\t" + func_exp_name
    mangled += ("\t" + normalize_string(rettype) +
                " (STDCALL *" + normalize_string(name) + ")(" + normalize_string(arg) + ")")
    mangled += ("\t" + normalize_string(rettype) + " " + normalize_string(name) +
                "(" + normalize_string(arg) + ")")
    mangled += "\t" + name
    mangled += "\t" + md5
    mangled += "\t" + get_arg_names(arg)
    mangled += ("\t" + normalize_string(rettype) +
                " (STDCALL * __functype)(" + normalize_string(except_arg_names(arg)) + ")")
    mangled += "\t" + normalize_string(rettype)
    if envname:
        mangled += "\t" + envname

    if envname:
        OFH.append("#ifdef " + envname + "\n")

    OFH.append("static ")
    OFH.append(normalize_string(rettype))
    OFH.append(" STDCALL ")
    OFH.append("TVP_Stub_" + md5 + "(")
    OFH.append(normalize_string(arg))
    OFH.append(")\n")
    OFH.append("{\n")
    argnames = get_arg_names(arg)
    OFH.append("\t")
    OFH.append("return ")
    OFH.append(name + "(" + argnames + ");\n")
    OFH.append("}\n")

    if envname:
        OFH.append("#else\n")
        OFH.append("static void STDCALL TVP_Stub_" + md5 + "(){}\n")
        OFH.append("#endif // " + envname + "\n")

    func_list.append(mangled)
    num += 1


def process_exp_stub(path):
    global defs, impls
    content = read_file(path)

    for m in re.finditer(r'/\*\[\*/(.*?)/\*\]\*/', content, flags=FLAGS):
        defs += m.group(1) + "\n"

    for m in re.finditer(r'/\*\[C\*/(.*?)/\*C\]\*/', content, flags=FLAGS):
        impls += m.group(1) + "\n"

    for m in re.finditer(r'TJS_EXP_FUNC_DEF_ENV\(\s*(.*?)\s*,\s*(.*?)\s*,\s*(.*?)\s*,\s*\((.*?)\)\s*\)',
                         content, flags=FLAGS):
        make_exp_stub(m.group(2), m.group(3), m.group(4), m.group(1))

    for m in re.finditer(r'TJS_EXP_FUNC_DEF\(\s*(.*?)\s*,\s*(.*?)\s*,\s*\((.*?)\)\s*\)',
                         content, flags=FLAGS):
        make_exp_stub(m.group(1), m.group(2), m.group(3))

    for m in re.finditer(r'TVP_GL_FUNC_PTR_EXTERN_DECL\(\s*(.*?)\s*,\s*(.*?)\s*,\s*\((.*?)\)\s*\)',
                         content, flags=FLAGS):
        make_exp_stub(m.group(1), m.group(2), m.group(3))


# --- file IO (latin-1, byte-preserving) ------------------------------------
CORE = None  # set in main


def read_file(rel):
    path = rel if os.path.isabs(rel) else os.path.join(CORE, rel)
    with open(path, 'r', encoding='latin-1', newline='') as f:
        return f.read()


def write_file(rel, text):
    # copy-if-differ: only rewrite when the bytes change, so unchanged outputs
    # keep their mtime and don't trigger a needless rebuild (this replaces the
    # old copy_if_differ.pl + FuncStubs.~cpp/~h tilde-temp dance).
    path = rel if os.path.isabs(rel) else os.path.join(CORE, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    data = text.encode('latin-1')
    try:
        with open(path, 'rb') as f:
            if f.read() == data:
                print("unchanged " + rel)
                return
    except FileNotFoundError:
        pass
    with open(path, 'wb') as f:
        f.write(data)
    print("wrote     " + rel)



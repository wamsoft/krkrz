"""ライセンステキスト圧縮収録ソース生成器

manifest.json に列挙したライセンス文 (フィールドは doc/LicenseSystem.md 参照) を
zlib deflate で圧縮し、C++ ソースへ埋め込む。3 モード:

  本体内蔵テーブル (既定):
    python licenses/gen_licenses_c.py
      → common/base/BuiltinLicenses.cpp (tTVPBuiltinLicenseEntry 配列)

  プラグイン用登録関数:
    python <core>/licenses/gen_licenses_c.py --mode plugin \
        --manifest <plugin>/licenses/manifest.json \
        --out <plugin>/LicensesGen.cpp --func RegisterMyPluginLicenses
      → tp_stub の TVPRegisterLicense を呼ぶ関数を生成。プラグインの
        リンク時コールバック (NCB_PRE_REGIST_CALLBACK 等) から呼ぶ。

  本体内モジュール用登録関数:
    python licenses/gen_licenses_c.py --mode module \
        --manifest <module>/licenses/manifest.json \
        --out <module>/LicensesGen.cpp --func RegisterXxxLicenses
      → 本体に静的リンクされるが manifest を分けたいモジュール向け。
        tp_stub ではなく LicenseIntf.h を直接使う (互換ガード無し)。

  一覧表 (Markdown):
    python licenses/gen_licenses_c.py --mode table \
        --plugins <umbrella>/src/plugins \
        --out <umbrella>/doc/guide/BundledLicenses.md --i18n <umbrella>/doc/i18n
      → 本体 / プラグイン / その他 (フォント) に分けた対応表を生成。
        種別は manifest の "license" フィールドをそのまま使う (推測しない)。
        --i18n を付けると <i18n>/<lang>/bundled_licenses.json がある言語ぶん
        BundledLicenses.<lang>.md も出す (固定文言は TABLE_TEXT、manifest 由来の
        日本語の文言はそのカタログで訳す。訳の無い文言は原文のまま出して警告)。

manifest のエントリに "when": "MACRO" を付けると、そのエントリ (バイト配列と
テーブル行/登録呼び出し) が #if defined(MACRO) で囲まれる。ビルド構成で
実際にはリンクされないコンポーネント (例: ThorVG の Lottie ローダを切ると
JerryScript / RapidJSON は 1 行もコンパイルされない) を、一覧へ載せない
ために使う。マクロは CMake 側の構成判定から定義する。

出力はバイト一致なら書き換えない (mtime 保護)。テキストは UTF-8 として
収録される (収録元が UTF-8/ASCII であること)。
"""
import argparse, hashlib, json, os, sys, zlib


def load_manifest(path):
    with open(path, encoding="utf-8") as f:
        doc = json.load(f)
    base = os.path.dirname(os.path.abspath(path))
    entries = []
    for e in doc["entries"]:
        fp = os.path.join(base, e["file"])
        with open(fp, "rb") as f:
            data = f.read()
        # 収録テキストは UTF-8 (BOM は剥がす)。CRLF は LF へ正規化
        if data.startswith(b"\xef\xbb\xbf"):
            data = data[3:]
        data = data.replace(b"\r\n", b"\n")
        entries.append((e["name"], e.get("group", ""), data, e.get("when") or None))
    return entries


def emit_bytes(name, data):
    lines = [f"static const unsigned char {name}[] = {{"]
    for i in range(0, len(data), 24):
        lines.append("\t" + "".join(f"{b}," for b in data[i:i + 24]))
    lines.append("};")
    return "\n".join(lines)


def cstr(s):
    # ASCII 前提の表示名 (非 ASCII は \uXXXX でエスケープ)
    out = []
    for ch in s:
        o = ord(ch)
        if ch in '"\\':
            out.append("\\" + ch)
        elif 0x20 <= o < 0x7f:
            out.append(ch)
        else:
            out.append(f"\\u{o:04x}" if o <= 0xffff else f"\\U{o:08x}")
    return '"' + "".join(out) + '"'


def generate(entries, mode, func):
    out = []
    out.append("/* generated by licenses/gen_licenses_c.py — 手編集禁止。")
    out.append("   licenses/manifest.json + licenses/texts/ を編集して再生成する。 */")
    out.append("")
    if mode in ("core", "module"):
        out.append('#include "tjsCommHead.h"')
        out.append('#include "LicenseIntf.h"')
    else:
        out.append('#include "tp_stub.h"')
        out.append("")
        out.append("/* License API 非対応バージョンの tp_stub / 本体ヘッダと組み合わせた")
        out.append("   ビルドでは登録をまるごとスキップして空関数になる (互換ガード)。 */")
        out.append("#ifdef TVP_HAS_LICENSE_API")
    out.append("")
    arrays = []
    table = []
    for i, (name, group, data, when) in enumerate(entries):
        comp = zlib.compress(data, 9)
        sym = f"lic_{i:02d}"
        arrays.append(f"/* {name} ({len(data)} -> {len(comp)} bytes) */")
        if when:
            arrays.append(f"#if defined({when})")
        arrays.append(emit_bytes(sym, comp))
        if when:
            arrays.append("#endif")
        table.append((name, group, sym, len(comp), len(data), when))
    out.extend(arrays)
    out.append("")
    if mode == "core":
        out.append("const tTVPBuiltinLicenseEntry TVPBuiltinLicenses[] = {")
        for name, group, sym, csz, osz, when in table:
            if when:
                out.append(f"#if defined({when})")
            out.append(f"\t{{ TJS_W({cstr(name)}), TJS_W({cstr(group)}), {sym}, {csz}, {osz} }},")
            if when:
                out.append("#endif")
        out.append("};")
        # 条件付きエントリがあるので件数は配列サイズから求める (手書き定数にしない)
        out.append("const int TVPBuiltinLicenseCount =")
        out.append("\tsizeof(TVPBuiltinLicenses) / sizeof(TVPBuiltinLicenses[0]);")
    else:
        out.append(f"void {func}()")
        out.append("{")
        # plugin: ビルド時の tp_stub が License API を持っていても、読み込む本体が古いと
        # TVPRegisterLicense が無く、tp_stub が「関数が無い」例外を投げてプラグインの
        # 読み込み自体が失敗する。登録は付加情報なので、例外は受け止めて登録を諦める。
        ind = "\t\t" if mode == "plugin" else "\t"
        if mode == "plugin":
            out.append("\ttry {")
        for name, group, sym, csz, osz, when in table:
            if when:
                out.append(f"#if defined({when})")
            out.append(f"{ind}TVPRegisterLicense(TJS_W({cstr(name)}), TJS_W({cstr(group)}), {sym}, {csz}, {osz});")
            if when:
                out.append("#endif")
        if mode == "plugin":
            out.append("\t} catch (...) {")
            out.append("\t\t/* 本体が License API を持たない (古い本体) ときは登録しない */")
            out.append("\t}")
        out.append("}")
        if mode == "plugin":
            out.append("")
            out.append("#else /* !TVP_HAS_LICENSE_API */")
            out.append("")
            out.append(f"void {func}() {{}}")
            out.append("")
            out.append("#endif /* TVP_HAS_LICENSE_API */")
    out.append("")
    return "\n".join(out)


